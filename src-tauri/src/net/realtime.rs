//! Realtime clients: WebSocket and Server-Sent Events (SSE).
//!
//! Both reuse the instrumented [`super::stream::connect_stream`] connector, so a
//! live stream reports the same DNS/TCP/TLS detail as a one-shot request. Events
//! are pushed to the frontend over a Tauri `Channel`; outgoing control (send on
//! a socket, close a stream) goes through per-connection registries keyed by id.

use crate::model::{Connection, DnsInfo, HttpRequest, NetworkInfo, Timings, TlsInfo};
use crate::net::{client, stream};
use bytes::Bytes;
use futures_util::{SinkExt, StreamExt};
use http::header::{HeaderName, HeaderValue};
use http_body_util::BodyExt;
use hyper_util::rt::TokioIo;
use serde::Serialize;
use std::collections::HashMap;
use std::sync::OnceLock;
use tauri::ipc::Channel;
use tokio::sync::{mpsc, Mutex};
use tokio_tungstenite::tungstenite::client::IntoClientRequest;
use tokio_tungstenite::tungstenite::Message;
use url::Url;

/// One event in a realtime stream, serialized to the frontend `Channel`.
#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase", tag = "kind")]
pub enum StreamEvent {
    /// Connection established — carries the handshake's network detail.
    Open {
        protocol: String,
        status: Option<u16>,
        timings: Timings,
        network: NetworkInfo,
    },
    /// A message was sent or received. `direction` is "sent" | "received".
    Message {
        direction: String,
        data: String,
        bytes: usize,
        binary: bool,
    },
    /// A non-message protocol event (ping/pong, retry hint, …).
    Info { message: String },
    /// A protocol or transport error (the stream usually ends after this).
    Error { message: String },
    /// The stream ended.
    Closed { reason: String },
}

enum WsCmd {
    Text(String),
    Close,
}

fn ws_registry() -> &'static Mutex<HashMap<String, mpsc::UnboundedSender<WsCmd>>> {
    static REG: OnceLock<Mutex<HashMap<String, mpsc::UnboundedSender<WsCmd>>>> = OnceLock::new();
    REG.get_or_init(|| Mutex::new(HashMap::new()))
}

/// SSE connections register a cancel sender BEFORE spawning the reader task, so
/// the task's self-removal on exit can never orphan an entry (dropping the
/// sender, e.g. from `sse_close`, cancels the task via its select! arm).
fn sse_registry() -> &'static Mutex<HashMap<String, mpsc::UnboundedSender<()>>> {
    static REG: OnceLock<Mutex<HashMap<String, mpsc::UnboundedSender<()>>>> = OnceLock::new();
    REG.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Build the handshake `Open` event from a freshly-connected stream.
fn open_event(conn_dns: DnsInfo, conn_tls: Option<TlsInfo>, connection: Connection, scheme: String, protocol: &str, status: Option<u16>, dns_ms: f64, tcp_ms: f64, tls_ms: f64) -> StreamEvent {
    let timings = Timings {
        dns_ms,
        tcp_ms,
        tls_ms,
        ttfb_ms: 0.0,
        download_ms: 0.0,
        total_ms: dns_ms + tcp_ms + tls_ms,
    };
    let network = NetworkInfo {
        dns: conn_dns,
        tls: conn_tls,
        connection,
        redirects: Vec::new(),
        hops: Vec::new(),
        request_size_bytes: 0,
        response_size_bytes: 0,
        scheme,
    };
    StreamEvent::Open {
        protocol: protocol.to_string(),
        status,
        timings,
        network,
    }
}

/// Collect the request's enabled headers + applied auth into a flat list.
fn flat_headers(req: &HttpRequest) -> Vec<(String, String)> {
    let mut headers: Vec<(String, String)> = Vec::new();
    for h in &req.headers {
        if h.enabled && !h.key.trim().is_empty() {
            headers.push((h.key.clone(), h.value.clone()));
        }
    }
    client::apply_auth(&req.auth, &mut headers);
    headers
}

// ---------------------------------------------------------------------------
// WebSocket
// ---------------------------------------------------------------------------

#[tauri::command]
pub async fn ws_connect(request: HttpRequest, on_event: Channel<StreamEvent>) -> Result<String, String> {
    let id = uuid::Uuid::new_v4().to_string();
    let url = normalize_ws_url(&request.url).map_err(|e| format!("{e:#}"))?;
    let is_tls = url.scheme() == "wss";

    let conn = stream::connect_stream(&url, is_tls, &request)
        .await
        .map_err(|e| format!("{e:#}"))?;
    let (dns, tls, mut connection, dns_ms, tcp_ms, tls_ms) =
        (conn.dns, conn.tls, conn.connection, conn.dns_ms, conn.tcp_ms, conn.tls_ms);
    connection.http_version = "WebSocket".to_string();

    // Build the client handshake request from the URL, then layer on user
    // headers + auth (Sec-WebSocket-* and Host are generated by tungstenite).
    let mut ws_req = url
        .as_str()
        .into_client_request()
        .map_err(|e| format!("invalid WebSocket request: {e}"))?;
    {
        let h = ws_req.headers_mut();
        for (k, v) in flat_headers(&request) {
            if let (Ok(name), Ok(val)) = (
                HeaderName::from_bytes(k.as_bytes()),
                HeaderValue::from_str(&v),
            ) {
                h.insert(name, val);
            }
        }
    }

    let (ws_stream, response) = tokio_tungstenite::client_async(ws_req, conn.stream)
        .await
        .map_err(|e| format!("WebSocket handshake failed: {e}"))?;

    let status = response.status().as_u16();
    let _ = on_event.send(open_event(
        dns, tls, connection, url.scheme().to_string(), "WebSocket", Some(status), dns_ms, tcp_ms, tls_ms,
    ));

    let (mut write, mut read) = ws_stream.split();
    let (tx, mut rx) = mpsc::unbounded_channel::<WsCmd>();
    ws_registry().lock().await.insert(id.clone(), tx);

    let ev = on_event.clone();
    let id_task = id.clone();
    tokio::spawn(async move {
        // Whether a terminal event (Closed/Error) was already emitted, so the
        // fallback below doesn't produce a duplicate "Closed" line.
        let mut announced = false;
        loop {
            tokio::select! {
                cmd = rx.recv() => match cmd {
                    Some(WsCmd::Text(t)) => {
                        let bytes = t.len();
                        if write.send(Message::Text(t.clone().into())).await.is_err() {
                            break;
                        }
                        let _ = ev.send(StreamEvent::Message {
                            direction: "sent".into(),
                            data: t,
                            bytes,
                            binary: false,
                        });
                    }
                    Some(WsCmd::Close) | None => {
                        let _ = write.send(Message::Close(None)).await;
                        break;
                    }
                },
                msg = read.next() => match msg {
                    Some(Ok(Message::Text(t))) => {
                        let s = t.to_string();
                        let _ = ev.send(StreamEvent::Message {
                            direction: "received".into(),
                            bytes: s.len(),
                            data: s,
                            binary: false,
                        });
                    }
                    Some(Ok(Message::Binary(b))) => {
                        let n = b.len();
                        let _ = ev.send(StreamEvent::Message {
                            direction: "received".into(),
                            data: format!("<{n} bytes binary>"),
                            bytes: n,
                            binary: true,
                        });
                    }
                    Some(Ok(Message::Ping(_))) => {
                        let _ = ev.send(StreamEvent::Info { message: "ping ←".into() });
                    }
                    Some(Ok(Message::Pong(_))) => {
                        let _ = ev.send(StreamEvent::Info { message: "pong ←".into() });
                    }
                    Some(Ok(Message::Close(frame))) => {
                        let reason = frame
                            .map(|f| format!("{} {}", f.code, f.reason))
                            .unwrap_or_else(|| "closed by server".into());
                        let _ = ev.send(StreamEvent::Closed { reason });
                        announced = true;
                        break;
                    }
                    Some(Ok(Message::Frame(_))) => {}
                    Some(Err(e)) => {
                        let _ = ev.send(StreamEvent::Error { message: e.to_string() });
                        announced = true;
                        break;
                    }
                    None => break,
                },
            }
        }
        ws_registry().lock().await.remove(&id_task);
        if !announced {
            let _ = ev.send(StreamEvent::Closed { reason: "connection closed".into() });
        }
    });

    Ok(id)
}

#[tauri::command]
pub async fn ws_send(id: String, text: String) -> Result<(), String> {
    let reg = ws_registry().lock().await;
    match reg.get(&id) {
        Some(tx) => tx
            .send(WsCmd::Text(text))
            .map_err(|_| "connection is closed".to_string()),
        None => Err("no such connection".to_string()),
    }
}

#[tauri::command]
pub async fn ws_close(id: String) -> Result<(), String> {
    if let Some(tx) = ws_registry().lock().await.remove(&id) {
        let _ = tx.send(WsCmd::Close);
    }
    Ok(())
}

/// Coerce a user-entered URL into a ws:// or wss:// URL.
fn normalize_ws_url(raw: &str) -> anyhow::Result<Url> {
    let raw = raw.trim();
    // Only rewrite the SCHEME prefix — not an http(s):// that appears inside the
    // path or query (e.g. a redirect-target query parameter).
    let with_scheme = if let Some(rest) = raw.strip_prefix("https://") {
        format!("wss://{rest}")
    } else if let Some(rest) = raw.strip_prefix("http://") {
        format!("ws://{rest}")
    } else if raw.contains("://") {
        raw.to_string()
    } else {
        format!("wss://{raw}")
    };
    let url = Url::parse(&with_scheme)?;
    if url.scheme() != "ws" && url.scheme() != "wss" {
        anyhow::bail!("WebSocket URL must use ws:// or wss://");
    }
    Ok(url)
}

